/** 依時間決定顯示哪一句：每 intervalSec 秒換下一句；同一時段大家看到的一樣，不會每次重繪亂跳 */
export function memeAt(state: DriverState, now: number, intervalSec: number): string {
  const list = MEMES[state];
  const i = Math.floor(now / 1000 / Math.max(5, intervalSec));
  return list[i % list.length]!;
}
