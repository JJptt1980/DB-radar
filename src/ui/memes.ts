/** 固定種子的洗牌（每次開 App 順序都一樣，才能保證一天內不重複） */
function shuffled<T>(arr: readonly T[], seed: number): T[] {
  const a = [...arr];
  let s = seed >>> 0;
  const rand = () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j]!, a[i]!];
  }
  return a;
}

const ORDER: Record<DriverState, Parts> = Object.fromEntries(
  (Object.keys(MEMES) as DriverState[]).map((s, k) => [
    s,
    { open: shuffled(MEMES[s].open, 11 + k), mid: shuffled(MEMES[s].mid, 101 + k), close: shuffled(MEMES[s].close, 1009 + k) },
  ]),
) as unknown as Record<DriverState, Parts>;

/** 這個狀態總共組得出幾句不同的句子 */
export const memeCount = (state: DriverState): number => {
  const p = MEMES[state];
  return p.open.length * p.mid.length * p.close.length;
};

/** 設定可選的切換間隔（秒） */
export const MEME_INTERVALS = [30, 60, 120, 300, 600] as const;

const DAY_MS = 86_400_000;
const TAIPEI_OFFSET_MS = 8 * 3_600_000;

/** 第 i 句（i 小於組合總數時絕不重複） */
export function memeByIndex(state: DriverState, i: number): string {
  const p = ORDER[state];
  const n = memeCount(state);
  const j = ((i % n) + n) % n;
  return `${p.open[j % p.open.length]}，${p.mid[j % p.mid.length]}。${p.close[j % p.close.length]}`;
}

/**
 * 依時間決定顯示哪一句：台北時間當天的第幾個間隔，再依日期錯開起點（每天開頭的句子不一樣）。
 */
export function memeAt(state: DriverState, now: number, intervalSec: number): string {
  const local = now + TAIPEI_OFFSET_MS;
  const day = Math.floor(local / DAY_MS);
  const slot = Math.floor((local - day * DAY_MS) / 1000 / Math.max(30, intervalSec));
  return memeByIndex(state, slot + day * 977);
}
